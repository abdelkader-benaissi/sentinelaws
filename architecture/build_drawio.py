def audit():
    problems = []
    icons = [n for n in NODES if n["kind"] == "icon"]
    groups = [n for n in NODES if n["kind"] == "group"]
    notes = [n for n in NODES if n["kind"] == "note"]

    # Every solid thing a connector or label must keep clear of.
    solids = []
    for n in icons:
        solids.append((n["id"], "icon", icon_box(n)))
        solids.append((n["id"], "label", label_box(n)))
    for n in groups:
        solids.append((n["id"], "title", title_box(n)))
    for n in notes:
        solids.append((n["id"], "note", note_box(n)))

    # 1. Icons, labels, titles and notes never overlap each other. An icon's
    #    own label touches its icon by construction.
    for i, (aid, akind, abox) in enumerate(solids):
        for bid, bkind, bbox in solids[i + 1:]:
            if aid == bid:
                continue
            if overlaps(abox, bbox, pad=2):
                problems.append(f"{aid} {akind} overlaps {bid} {bkind}")

    # 2. Containment: an icon (with its label) that touches a container must
    #    sit fully inside it, unless it is declared to span containers.
    for n in icons:
        box = union(icon_box(n), label_box(n))
        allowed = span_allowance(n, groups)
        for g in groups:
            gbox = group_box(g)
            if g["id"] in allowed:
                continue
            if overlaps(box, gbox) and not contains(gbox, box):
                problems.append(f"{n['id']} straddles {g['id']}")

    # 3. Containers either nest or are declared to span.
    for i, a in enumerate(groups):
        for b in groups[i + 1:]:
            abox, bbox = group_box(a), group_box(b)
            if not overlaps(abox, bbox):
                continue
            if contains(abox, bbox) or contains(bbox, abox):
                continue
            if b["id"] in span_allowance(a, groups) or \
                    a["id"] in span_allowance(b, groups):
                continue
            problems.append(f"containers {a['id']} and {b['id']} overlap")

    # 4. Spanning elements really span what they claim.
    for n in icons + groups:
        if not n.get("spans"):
            continue
        box = icon_box(n) if n["kind"] == "icon" else group_box(n)
        for target in n["spans"]:
            tbox = group_box(BY_ID[target])
            if not overlaps(box, tbox) or contains(tbox, box):
                problems.append(f"{n['id']} does not span {target}")

    # 5. Connectors: orthogonal, clear of icons/labels/titles/notes (except
    #    their own two icons), and no shared segments between connectors.
    segments = []
    for idx, e in enumerate(EDGES):
        pts = e["points"]
        name = f"{e['src']}->{e['dst']}"
        for p, q in zip(pts, pts[1:]):
            if p[0] != q[0] and p[1] != q[1]:
                problems.append(f"{name}: diagonal segment {p}->{q}")
            if p == q:
                problems.append(f"{name}: zero-length segment at {p}")
            for sid, skind, sbox in solids:
                if skind == "icon" and sid in (e["src"], e["dst"]):
                    continue
                if segment_hits(p, q, sbox):
                    problems.append(f"{name} runs through {sid} {skind}")
            segments.append((idx, name, p, q))
        lbox = edge_label_box(e)
        if lbox:
            for sid, skind, sbox in solids:
                if overlaps(lbox, sbox, pad=1):
                    problems.append(f"label of {name} overlaps {sid} {skind}")
            e["_lbox"] = lbox

    for i, (ia, na, pa, qa) in enumerate(segments):
        for ib, nb, pb, qb in segments[i + 1:]:
            if ia != ib and collinear_overlap(pa, qa, pb, qb):
                problems.append(f"{na} and {nb} share a segment")

    labelled = [e for e in EDGES if e.get("_lbox")]
    for i, a in enumerate(labelled):
        for b in labelled[i + 1:]:
            if overlaps(a["_lbox"], b["_lbox"], pad=2):
                problems.append(
                    f"labels of {a['src']}->{a['dst']} and "
                    f"{b['src']}->{b['dst']} overlap")
        for idx, name, p, q in segments:
            if EDGES[idx] is a:
                continue
            if segment_hits(p, q, a["_lbox"]):
                problems.append(f"{name} runs through the label of "
                                f"{a['src']}->{a['dst']}")

    for n in NODES:
        if n["x"] < 0 or n["y"] < 0:
            problems.append(f"{n['id']} has a negative coordinate")
    return problems


def span_allowance(node, groups):
    """Containers a spanning node may cross: the spanned ones and parents."""
    if not node.get("spans"):
        return set()
    allowed = set(node["spans"])
    for target in node["spans"]:
        tbox = group_box(BY_ID[target])
        allowed.update(g["id"] for g in groups
                       if contains(group_box(g), tbox))
    # A spanning group also crosses everything nested between its parents.
    box = icon_box(node) if node["kind"] == "icon" else group_box(node)
    allowed.update(g["id"] for g in groups
                   if g["id"] != node["id"] and g["group"] == "az"
                   and overlaps(group_box(g), box))
    return allowed


def segment_hits(p, q, box, pad=1.0):
    x0, y0, x1, y1 = box[0] + pad, box[1] + pad, box[2] - pad, box[3] - pad
    if x0 >= x1 or y0 >= y1:
        return False
    if p[1] == q[1]:                       # horizontal
        lo, hi = sorted((p[0], q[0]))
        return y0 < p[1] < y1 and lo < x1 and hi > x0
    if p[0] == q[0]:                       # vertical
        lo, hi = sorted((p[1], q[1]))
        return x0 < p[0] < x1 and lo < y1 and hi > y0
    return False


def collinear_overlap(pa, qa, pb, qb):
    if pa[1] == qa[1] == pb[1] == qb[1]:
        a0, a1 = sorted((pa[0], qa[0]))
        b0, b1 = sorted((pb[0], qb[0]))
        return min(a1, b1) - max(a0, b0) > 0.5
    if pa[0] == qa[0] == pb[0] == qb[0]:
        a0, a1 = sorted((pa[1], qa[1]))
        b0, b1 = sorted((pb[1], qb[1]))
        return min(a1, b1) - max(a0, b0) > 0.5
    return False


def crossings():
    """Perpendicular connector crossings (allowed, but kept few)."""
    segs = [(i, p, q) for i, e in enumerate(EDGES)
            for p, q in zip(e["points"], e["points"][1:])]
    found = []
    for a in range(len(segs)):
        for b in range(a + 1, len(segs)):
            ia, pa, qa = segs[a]
            ib, pb, qb = segs[b]
            if ia == ib:
                continue
            h, v = None, None
            if pa[1] == qa[1] and pb[0] == qb[0]:
                h, v = (pa, qa), (pb, qb)
            elif pb[1] == qb[1] and pa[0] == qa[0]:
                h, v = (pb, qb), (pa, qa)
            if not h:
                continue
            hx0, hx1 = sorted((h[0][0], h[1][0]))
            vy0, vy1 = sorted((v[0][1], v[1][1]))
            if hx0 < v[0][0] < hx1 and vy0 < h[0][1] < vy1:
                found.append((EDGES[ia], EDGES[ib]))
    return found


