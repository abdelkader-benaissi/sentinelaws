def build_xml() -> str:
    lines = [
        '<mxfile host="app.diagrams.net" type="device">',
        '  <diagram id="sentinelaws" name="SentinelAWS">',
        '    <mxGraphModel dx="1600" dy="1200" grid="0" gridSize="10" '
        'guides="1" tooltips="1" connect="1" arrows="1" fold="1" page="1" '
        'pageScale="1" pageWidth="3140" pageHeight="1760" math="0" '
        'shadow="0">',
        "      <root>",
        '        <mxCell id="0"/>',
        '        <mxCell id="1" parent="0"/>',
    ]
    # Containers first (outermost first), then notes, icons and connectors,
    # so connectors are never hidden under a filled subnet.
    order = ([n for n in NODES if n["kind"] == "group"]
             + [n for n in NODES if n["kind"] == "note"]
             + [n for n in NODES if n["kind"] == "icon"])
    for n in order:
        lines.append(
            f'        <mxCell id="{n["id"]}" value="{esc(node_value(n))}" '
            f'style="{esc(node_style(n))}" vertex="1" parent="1">')
        lines.append(
            f'          <mxGeometry x="{n["x"]:g}" y="{n["y"]:g}" '
            f'width="{n["w"]:g}" height="{n["h"]:g}" as="geometry"/>')
        lines.append("        </mxCell>")
    for i, e in enumerate(EDGES, start=1):
        middle = "".join(f'<mxPoint x="{x:g}" y="{y:g}"/>'
                         for x, y in e["points"][1:-1])
        array = f'<Array as="points">{middle}</Array>' if middle else ""
        geometry_x = f' x="{e["at"]:g}"' if e["at"] else ""
        lines.append(
            f'        <mxCell id="e{i}" value="{esc(e["label"])}" '
            f'style="{esc(edge_style(e))}" edge="1" parent="1" '
            f'source="{e["src"]}" target="{e["dst"]}">')
        lines.append(f'          <mxGeometry{geometry_x} relative="1" '
                     f'as="geometry">{array}</mxGeometry>')
        lines.append("        </mxCell>")
    lines += legend_cells()
    lines += ["      </root>", "    </mxGraphModel>", "  </diagram>",
              "</mxfile>"]
    return "\n".join(lines) + "\n"


def main(argv):
    problems = audit()
    if problems:
        for problem in problems:
            print("LAYOUT: " + problem)
        if "--force" not in argv:   # --force: write anyway, for layout work
            return 2
    cross = crossings()
    if "--verbose" in argv:
        for a, b in cross:
            print(f"crossing: {a['src']}->{a['dst']} x {b['src']}->{b['dst']}")

    xml = build_xml()
    ET.fromstring(xml)  # well-formedness gate

    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text() != xml:
            print(f"{OUT.name} is stale; run python3 architecture/build_drawio.py")
            return 1
        print("architecture/sentinelaws.drawio is up to date")
        return 0

    OUT.write_text(xml)
    print(f"wrote {OUT.name}: {len(NODES)} nodes, {len(EDGES)} connectors, "
          f"{len(cross)} crossings")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
