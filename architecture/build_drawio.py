def esc(value: str) -> str:
    return (value.replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def node_value(n):
    if n["kind"] == "icon":
        html = n["title"].replace("\n", "<br>")
        if n.get("sub"):
            sub = n["sub"].replace("\n", "<br>")
            html += (f"<br><font style=\"font-size:10px;color:#545B64\">"
                     f"{sub}</font>")
        return html
    if n["kind"] == "group":
        return n["title"].replace("\n", "<br>")
    return n["text"]


def node_style(n):
    if n["kind"] == "icon":
        style = n["style"].format(fill=n["fill"], icon=n["icon"],
                                  label=LABEL_STYLE[n["label"]])
        if n.get("label_bg"):
            style += f"labelBackgroundColor={n['label_bg']};"
        return style
    if n["kind"] == "group":
        style = GROUP_STYLE[n["group"]]
        return style.format(align=n["align"]) if "{align}" in style else style
    bold = "fontStyle=1;" if n["bold"] else ""
    return (f"rounded=1;arcSize=6;fillColor={n['fill']};strokeColor=#CBD5E1;"
            f"verticalAlign=middle;align=left;spacingLeft=10;"
            f"fontColor=#1E293B;fontSize={n['size']};{bold}html=1;"
            f"whiteSpace=wrap;")


def edge_style(e):
    sx, sy = constraint(e["src"], e["points"][0])
    tx, ty = constraint(e["dst"], e["points"][-1])
    dash = "dashed=1;dashPattern=6 4;" if e["dashed"] else ""
    return (f"edgeStyle=none;rounded=1;arcSize=12;html=1;"
            f"strokeColor={e['color']};strokeWidth=2;{dash}"
            f"endArrow=block;endFill=1;endSize=6;"
            f"exitX={sx:g};exitY={sy:g};exitDx=0;exitDy=0;exitPerimeter=0;"
            f"entryX={tx:g};entryY={ty:g};entryDx=0;entryDy=0;"
            f"entryPerimeter=0;fontColor={e['color']};fontSize={EDGE_FONT};"
            f"labelBackgroundColor=#FFFFFF;")


def constraint(node_id, point):
    """Relative exit/entry point of a border point, for draw.io."""
    x0, y0, x1, y1 = box_of(BY_ID[node_id])
    return (round((point[0] - x0) / (x1 - x0), 4),
            round((point[1] - y0) / (y1 - y0), 4))


