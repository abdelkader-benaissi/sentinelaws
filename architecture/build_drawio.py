def text_size(lines):
    """(width, height) of a list of (text, font size) lines."""
    width = max(len(text) * size * CHAR_W for text, size in lines)
    height = sum(size * LINE_H for _, size in lines)
    return width + 4, height + 2


def label_lines(node):
    lines = [(part, 12) for part in node["title"].split("\n")]
    if node.get("sub"):
        lines += [(part, 10) for part in node["sub"].split("\n")]
    return lines


def icon_box(node):
    return (node["x"], node["y"], node["x"] + node["w"], node["y"] + node["h"])


def label_box(node):
    w, h = text_size(label_lines(node))
    x0, y0, x1, y1 = icon_box(node)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    pos = node["label"]
    if pos == "below":
        return (cx - w / 2, y1 + 1, cx + w / 2, y1 + 1 + h)
    if pos == "above":
        return (cx - w / 2, y0 - 1 - h, cx + w / 2, y0 - 1)
    if pos == "left":
        return (x0 - 3 - w, cy - h / 2, x0 - 3, cy + h / 2)
    if pos == "right":
        return (x1 + 3, cy - h / 2, x1 + 3 + w, cy + h / 2)
    if pos == "tl":
        return (x0 - w, y0 - h, x0, y0)
    if pos == "tr":
        return (x1, y0 - h, x1 + w, y0)
    raise ValueError(pos)


def group_box(node):
    return (node["x"], node["y"], node["x"] + node["w"], node["y"] + node["h"])


def title_box(node):
    """Area covered by a container's title (and its group icon)."""
    lines = [(part, 12) for part in node["title"].split("\n")]
    w, h = text_size(lines)
    x0, y0, x1, _ = group_box(node)
    if node["group"] == "asg":
        cx = (x0 + x1) / 2
        w = max(w, 32)
        return (cx - w / 2, y0, cx + w / 2, y0 + 26 + h)
    if node["group"] in ("az", "generic"):
        if node["align"] == "right":
            return (x1 - 10 - w, y0, x1, y0 + 6 + h)
        if node["align"] == "center":
            cx = (x0 + x1) / 2
            return (cx - w / 2, y0, cx + w / 2, y0 + 6 + h)
        return (x0, y0, x0 + 10 + w, y0 + 6 + h)
    return (x0, y0, x0 + 30 + w, y0 + max(h, 25) + 4)


def note_box(node):
    return group_box(node)


def union(a, b):
    return (min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3]))


def overlaps(a, b, pad=0.0):
    return not (a[2] + pad <= b[0] or b[2] + pad <= a[0]
                or a[3] + pad <= b[1] or b[3] + pad <= a[1])


def contains(outer, inner):
    return (outer[0] <= inner[0] and outer[1] <= inner[1]
            and inner[2] <= outer[2] and inner[3] <= outer[3])


def box_of(node):
    return icon_box(node) if node["kind"] == "icon" else group_box(node)


def port(node, side, at=None):
    """A point on the border of a node.

    ``side`` is t, b, l or r; ``at`` is the absolute x (top/bottom) or y
    (left/right) coordinate on that side, or None for the middle.
    """
    x0, y0, x1, y1 = box_of(node)
    if side in "tb":
        x = (x0 + x1) / 2 if at is None else at
        if not x0 <= x <= x1:
            raise SystemExit(f"port x={x} outside {node['id']}")
        return (x, y0 if side == "t" else y1)
    y = (y0 + y1) / 2 if at is None else at
    if not y0 <= y <= y1:
        raise SystemExit(f"port y={y} outside {node['id']}")
    return (x0 if side == "l" else x1, y)


def edge(src, dst, label, color, *, out="r", into="l", via=(),
         dashed=False, at=0.0):
    """A connector from src to dst through orthogonal waypoints.

    ``out``/``into`` pin the start and end to a side of the source and target:
    "r" for the middle of the right side, or ("r", 512) for y=512 on it.
    ``via`` lists the bends. ``at`` moves the label along the connector
    (-1 = source end, 0 = middle, 1 = target end).
    """
    out = (out, None) if isinstance(out, str) else out
    into = (into, None) if isinstance(into, str) else into
    points = [port(BY_ID[src], *out), *via, port(BY_ID[dst], *into)]
    EDGES.append({"src": src, "dst": dst, "label": label, "color": color,
                  "points": points, "dashed": dashed, "at": at})


def path_length(points):
    return sum(abs(q[0] - p[0]) + abs(q[1] - p[1])
               for p, q in zip(points, points[1:]))


def point_along(points, distance):
    for p, q in zip(points, points[1:]):
        seg = abs(q[0] - p[0]) + abs(q[1] - p[1])
        if distance <= seg and seg:
            t = distance / seg
            return (p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t)
        distance -= seg
    return points[-1]


def edge_label_box(e):
    if not e["label"]:
        return None
    w, h = text_size([(e["label"], EDGE_FONT)])
    total = path_length(e["points"])
    cx, cy = point_along(e["points"], (e["at"] + 1) / 2 * total)
    return (cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2)


