#!/usr/bin/env python3
"""Generate the SentinelAWS architecture diagram as an editable draw.io file.

The .drawio file is the source of truth for the diagram and is generated by
this script so that the layout can be checked, not hand-nudged:

  * Every shape comes from the official AWS Architecture Icons as shipped in
    draw.io's AWS4 library, with the library's own styles: service icons
    (``resourceIcon``) for AWS services, resource glyphs for resources such as
    the NAT gateway or an EC2 instance, and the AWS group shapes for the AWS
    Cloud, Region, VPC, Availability Zones, subnets and the Auto Scaling group.
    Nothing is vendored, recoloured or stretched.
  * Every connector is drawn through explicit, orthogonal waypoints, and its
    start and end are pinned to the icon border, so what the checker below
    reasons about is exactly what draw.io renders.
  * The checker refuses to write a diagram in which icons, labels, container
    titles or connector labels overlap, a connector runs through an icon, a
    label or a container title, or two connectors share a segment.

Usage:

    python3 architecture/build_drawio.py            # write the .drawio
    python3 architecture/build_drawio.py --check     # fail if the file is stale
    python3 architecture/build_drawio.py --verbose   # also list line crossings
    python3 architecture/build_drawio.py --force     # write despite problems
                                                     # (layout work only)

Rendering to SVG/PNG is done by draw.io itself (desktop CLI or diagrams.net),
not by this script; see the README.

Every node and container mirrors a Terraform resource or AWS-managed
behaviour, so a change to terraform/ that is not reflected here is visible in
review.
"""

