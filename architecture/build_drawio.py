NODES: list[dict] = []
EDGES: list[dict] = []
BY_ID: dict[str, dict] = {}


def _add(node):
    if node["id"] in BY_ID:
        raise SystemExit(f"duplicate id {node['id']}")
    NODES.append(node)
    BY_ID[node["id"]] = node
    return node


def service(id_, icon, category, x, y, title, sub=None, label="below",
            size=56):
    """An AWS service icon (square, category colour)."""
    return _add({"kind": "icon", "id": id_, "x": x, "y": y, "w": size,
                 "h": size, "style": SERVICE_STYLE, "icon": icon,
                 "fill": CATEGORY[category], "title": title, "sub": sub,
                 "label": label, "spans": None})


def resource(id_, icon, category, x, y, title, sub=None, label="below",
             w=48, h=48, spans=None, label_bg=None):
    """An AWS resource glyph (no background square)."""
    return _add({"kind": "icon", "id": id_, "x": x, "y": y, "w": w, "h": h,
                 "style": RESOURCE_STYLE, "icon": icon,
                 "fill": CATEGORY[category], "title": title, "sub": sub,
                 "label": label, "spans": spans, "label_bg": label_bg})


def group(id_, kind, x, y, w, h, title, spans=None, align="left"):
    return _add({"kind": "group", "id": id_, "group": kind, "x": x, "y": y,
                 "w": w, "h": h, "title": title, "spans": spans,
                 "align": align})


def note(id_, x, y, w, h, text, size=11, bold=False, fill="#F8FAFC"):
    return _add({"kind": "note", "id": id_, "x": x, "y": y, "w": w, "h": h,
                 "text": text, "size": size, "bold": bold, "fill": fill})


